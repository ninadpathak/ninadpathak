"""Code blocks: build-time markup and the syntax theme.

Python-Markdown's codehilite runs Pygments at build time and hands each fenced block to
CodeBlockFormatter, which wraps Pygments' `<div class="highlight">` in a frame with a head
strip naming the language. The copy button is added by static/js/main.js, because a button
that can't work without script shouldn't ship in the HTML. Styles live in
static/css/code-blocks.css; the token colors below are written to highlight.css.

Two layouts, chosen from the fence's info string:
- Code (bash, python, json, ...) keeps its lines and scrolls sideways, with an edge fade
  that only appears when there is more to see. Wrapping code changes what it says.
- Prose-like blocks (text, markdown, prompt, or no language) soft-wrap. They hold prompts,
  templates and tool output whose lines run to 300 characters, which nobody should scroll.

The theme is the site palette: ink for text, the accent for keywords, one green for
strings, one blue for numbers, constants and keys, muted italics for comments. Every token
class clears WCAG AA (4.5:1) against the code background in both themes;
tests/test_code_blocks.py checks every Pygments token type, not just the ones in use.
"""
from __future__ import annotations

import html
import re

from pygments.formatters import HtmlFormatter
from pygments.style import Style
from pygments.token import (
    Comment, Error, Generic, Keyword, Name, Number, Operator, Punctuation, String, Text, Token,
)

WRAP_LANGS = {"text", "markdown", "md", "prompt", "plaintext", "txt"}

# Background and roles per theme. The backgrounds are the site's --bg-1 surface; the roles
# are site tokens (main.css) except green and blue, which exist only for code.
