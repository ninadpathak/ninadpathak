#!/usr/bin/env node
// Write a share-card source for every published post (and every pending post) in og-cards.json.
//
//   node og.mjs            write content/diagrams/<slug>/og.mmd for each mapped post
//   node og.mjs --check    exit 1 only if a generated source is out of date with the map;
//                          a published post without a card is a warning (it keeps the
//                          site's default image)
//
// A source holds only the glyph chain. The title, category, and URL are read from the post
// when render.mjs runs, so publishing or retitling a post never edits a hashed file.
// A hand-written og.mmd (no GENERATED marker) is never overwritten.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { REPO_DIR, TOOL_DIR } from './lib/tokens.mjs';
import { publishedPosts } from './lib/posts.mjs';

const CHECK = process.argv.includes('--check');
const MARK = '%% GENERATED by tools/image-brand/og.mjs from og-cards.json; edit the map, not this file';

const cards = JSON.parse(readFileSync(path.join(TOOL_DIR, 'og-cards.json'), 'utf8'));
const pending = cards.$pending || {};
const published = new Set(publishedPosts().map((p) => p.slug));
const slugs = Object.keys(cards).filter((k) => !k.startsWith('$')).sort();

const warnings = [], problems = [];
for (const slug of published) if (!cards[slug] && !existsSync(path.join(REPO_DIR, 'content/diagrams', slug, 'og.mmd'))) warnings.push(`${slug}: published post has no share card; it keeps the site default image (add it to og-cards.json)`);
for (const slug of slugs) if (!published.has(slug) && !pending[slug]) warnings.push(`og-cards.json maps "${slug}", which is neither published nor listed in $pending`);

let written = 0;
for (const slug of slugs) {
  const target = path.join(REPO_DIR, 'content/diagrams', slug, 'og.mmd');
  const existing = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (existing && !existing.startsWith(MARK)) continue; // hand-written card
  const chain = cards[slug];
  const ids = chain.map((_, i) => `g${i + 1}`);
  const focal = chain.findIndex((g) => g.endsWith('*'));
  const body = [
    MARK,
    '%% @kind og',
    `%% @path ${ids.join('>')}`,
    '%% @spacing 20,22',
    ...chain.map((g, i) => `%% @glyph ${ids[i]} | ${g.replace(/\*$/, '').trim()}`),
    'flowchart TB',
    ...ids.map((id, i) => `  ${id}[" "]${i === focal ? ':::focal' : ''}`),
    ...ids.slice(1).map((id, i) => `  ${ids[i]} --> ${id}`),
    '',
  ].join('\n');
  if (existing === body) continue;
  if (CHECK) { problems.push(`${slug}: og.mmd is out of date with og-cards.json; run node tools/image-brand/og.mjs`); continue; }
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, body);
  written += 1;
}
for (const w of warnings) console.warn(`warn ${w}`);
for (const p of problems) console.error(`FAIL ${p}`);
if (!CHECK) console.log(`${written} share-card sources written; ${published.size} published posts, ${Object.keys(pending).length} pending`);
process.exit(problems.length ? 1 : 0);
