#!/usr/bin/env node
// Write a share-card source for every published post from og-cards.json.
//
//   node og.mjs            write content/diagrams/<slug>/og.mmd for each mapped post
//   node og.mjs --check    exit 1 if a published post has no card, a map entry has no post,
//                          or a generated source is out of date
//
// A hand-written og.mmd (no GENERATED marker) is never overwritten.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { REPO_DIR, TOOL_DIR } from './lib/tokens.mjs';

const CHECK = process.argv.includes('--check');
const MARK = '%% GENERATED by tools/image-brand/og.mjs from og-cards.json; edit the map, not this file';
const KICKERS = { 'ai-engineering': 'AI engineering', 'technical-documentation': 'Technical documentation', 'developer-experience': 'Developer experience' };

// Read the few frontmatter fields the card needs (title, slug, category, status).
function frontmatter(file) {
  const text = readFileSync(file, 'utf8');
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return {};
  const out = {};
  const lines = m[1].split('\n');
  for (let i = 0; i < lines.length; i++) {
    const kv = lines[i].match(/^([a-z_]+):\s*(.*)$/);
    if (!kv) continue;
    let v = kv[2];
    while (i + 1 < lines.length && /^\s+\S/.test(lines[i + 1]) && !/^\s*-/.test(lines[i + 1])) v += ` ${lines[++i].trim()}`;
    if (/^'.*'$/.test(v)) v = v.slice(1, -1).replace(/''/g, "'");
    else if (/^".*"$/.test(v)) v = JSON.parse(v);
    out[kv[1]] = v;
  }
  return out;
}

const cards = JSON.parse(readFileSync(path.join(TOOL_DIR, 'og-cards.json'), 'utf8'));
const postsDir = path.join(REPO_DIR, 'content/posts');
const posts = readdirSync(postsDir).filter((f) => f.endsWith('.md')).map((f) => ({ file: f, ...frontmatter(path.join(postsDir, f)) }))
  .filter((p) => p.status === 'published').map((p) => ({ ...p, slug: p.slug || p.file.replace(/\.md$/, '') }));

const problems = [];
const bySlug = new Set(posts.map((p) => p.slug));
for (const slug of Object.keys(cards)) if (slug !== '$comment' && !bySlug.has(slug)) problems.push(`og-cards.json maps "${slug}", which is not a published post`);

let written = 0;
for (const post of posts.sort((a, b) => a.slug.localeCompare(b.slug))) {
  const target = path.join(REPO_DIR, 'content/diagrams', post.slug, 'og.mmd');
  const existing = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (existing && !existing.startsWith(MARK)) continue; // hand-written card
  const chain = cards[post.slug];
  if (!chain) { problems.push(`${post.slug}: published post has no share card (add it to og-cards.json)`); continue; }
  const ids = chain.map((_, i) => `g${i + 1}`);
  const focal = chain.findIndex((g) => g.endsWith('*'));
  const lines = [
    MARK,
    '%% @kind og',
    `%% @og-kicker ${KICKERS[post.category] || 'Article'}`,
    `%% @og-title ${post.title}`,
    `%% @og-url ninadpathak.com/articles/${post.slug}/`,
    `%% @path ${ids.join('>')}`,
    '%% @spacing 20,22',
    ...chain.map((g, i) => `%% @glyph ${ids[i]} | ${g.replace(/\*$/, '').trim()}`),
    'flowchart TB',
    ...ids.map((id, i) => `  ${id}[" "]${i === focal ? ':::focal' : ''}`),
    ...ids.slice(1).map((id, i) => `  ${ids[i]} --> ${id}`),
    '',
  ];
  const body = lines.join('\n');
  if (existing === body) continue;
  if (CHECK) { problems.push(`${post.slug}: og.mmd is out of date; run node tools/image-brand/og.mjs`); continue; }
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, body);
  written += 1;
}
for (const p of problems) console.error(`FAIL ${p}`);
if (!CHECK) console.log(`${written} share-card sources written, ${posts.length} published posts`);
process.exit(problems.length ? 1 : 0);
