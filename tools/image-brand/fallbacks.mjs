#!/usr/bin/env node
// Static fallbacks for the two kept interactive visuals (GUIDELINE.md §13).
//
// Each visual page draws a complete picture without JavaScript. This script lifts that
// <svg id="plot"> out of the page with the page's own stylesheet, pins the light or dark
// theme, embeds subset fonts, and writes static/visuals/<name>.fallback-{light,dark}.svg.
// The article layers the fallback under the iframe, so a blocked or failed frame still
// shows the drawing (static/js/main.js reveals the frame once its page has run).
//
//   node fallbacks.mjs           write the fallbacks
//   node fallbacks.mjs --check   exit 1 if a committed fallback differs from a fresh one
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const VISUALS = path.join(ROOT, 'static/visuals');
const KEPT = ['cosine-similarity', 'matryoshka-truncation'];
const FACES = [
  ['Inter', 500, '@fontsource/inter/files/inter-latin-500-normal.woff2'],
  ['JetBrains Mono', 500, '@fontsource/jetbrains-mono/files/jetbrains-mono-latin-500-normal.woff2'],
];
const check = process.argv.includes('--check');

let stale = 0;
for (const name of KEPT) {
  const html = readFileSync(path.join(VISUALS, `${name}.html`), 'utf8');
  const svg = html.match(/<svg id="plot"[\s\S]*?<\/svg>/)[0];
  const css = html.match(/<style>([\s\S]*?)<\/style>/)[1];
  const text = [...svg.matchAll(/>([^<>]+)</g)].map((m) => m[1]).join('') + '0123456789';
  const fonts = [];
  for (const [family, weight, mod] of FACES) {
    const woff2 = await subsetFont(readFileSync(require.resolve(mod)), text, { targetFormat: 'woff2' });
    fonts.push(`@font-face{font-family:'${family}';font-weight:${weight};font-style:normal;src:url(data:font/woff2;base64,${woff2.toString('base64')}) format('woff2');}`);
  }
  const [, viewBox] = svg.match(/viewBox="([^"]+)"/);
  const [, , w, h] = viewBox.split(' ').map(Number);
  for (const theme of ['light', 'dark']) {
    const out = svg
      .replace('<svg id="plot"', `<svg xmlns="http://www.w3.org/2000/svg" data-theme="${theme}" width="${w}" height="${h}"`)
      .replace(/ id="(cs|mt)-(title|desc)"/g, '')
      .replace(/ aria-labelledby="[^"]*"/, '')
      .replace(/(<svg[^>]*>)/, `$1<style>${fonts.join('')}${css.trim()}</style>`);
    const file = path.join(VISUALS, `${name}.fallback-${theme}.svg`);
    const doc = `<!-- Generated by tools/image-brand/fallbacks.mjs from ${name}.html. Do not edit. -->\n${out}\n`;
    if (check) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== doc) { stale++; console.error(`stale ${path.relative(ROOT, file)}`); }
    } else {
      writeFileSync(file, doc);
      console.log(`${name} -> ${path.relative(ROOT, file)} (${Math.round(doc.length / 1024)} KB)`);
    }
  }
}
if (stale) { console.error(`${stale} fallback(s) differ from their visual; run node tools/image-brand/fallbacks.mjs`); process.exit(1); }
